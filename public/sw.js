// The build fills these with every floor, hashed data and the map's static assets.
// The client defers registration until the displayed map and search are idle.
const PRECACHE_REVISION = 'development';
const APP_SHELL_URLS = [];
const STATIC_CACHE_NAME = `rits-oic-map-static-v25-${PRECACHE_REVISION}`;
const RUNTIME_CACHE_NAME = `rits-oic-map-runtime-v25-${PRECACHE_REVISION}`;
const CACHE_PREFIX = 'rits-oic-map-';
const STATIC_PATH_PREFIXES = ['/assets/', '/food-marks/', '/iconsvg/', '/icon/', '/timetable/data/'];

function isEditorPath(pathname) {
  return pathname === '/editor' || pathname.startsWith('/editor/');
}

async function notifyOfflineState(state) {
  const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
  for (const client of clients) client.postMessage({ type: 'OFFLINE_MAP_STATUS', state, revision: PRECACHE_REVISION });
}

async function saveOfflineMap() {
  if (!APP_SHELL_URLS.length) throw new Error('Offline assets were not generated by the build.');
  const cache = await caches.open(STATIC_CACHE_NAME);
  await notifyOfflineState('saving');
  try {
    // A single low-priority request avoids competing with the displayed map.
    // Hashed assets reuse downloads already made by the initial page load.
    for (const url of APP_SHELL_URLS) {
      const response = await fetch(new Request(url, {
        cache: url.startsWith('/assets/') ? 'force-cache' : 'reload',
        priority: 'low',
      }));
      if (!response.ok || response.redirected) throw new Error(`Offline asset unavailable: ${url}`);
      await cache.put(url, response);
    }
    await notifyOfflineState('ready');
  } catch (error) {
    await caches.delete(STATIC_CACHE_NAME);
    await notifyOfflineState('error');
    throw error;
  }
}

async function networkFirst(request) {
  try {
    const response = await fetch(request);
    if (response.status < 500) return response;
  } catch {
    // Keep the URL's language, query and hash when opening a saved map.
  }
  const url = new URL(request.url);
  const pathname = ['/', '/en', '/en/'].includes(url.pathname)
    ? (url.pathname === '/' ? '/index.html' : '/en/index.html') : url.pathname;
  const cachedResponse = await (await caches.open(STATIC_CACHE_NAME)).match(pathname);
  if (cachedResponse) return cachedResponse;

  // Unsupported pages must not silently become the map at a different URL.
  const english = url.pathname.startsWith('/en/');
  return new Response(`<!doctype html><html lang="${english ? 'en' : 'ja'}"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${english ? 'Connection required' : 'オンライン接続が必要です'}</title><body><main><h1>${english ? 'Connection required' : 'オンライン接続が必要です'}</h1><p>${english ? 'This page needs an internet connection. Saved maps and classroom search are available offline.' : 'このページの表示には通信が必要です。保存済みの地図と教室検索はオフラインで利用できます。'}</p><a href="${english ? '/en/' : '/'}">${english ? 'Open the map' : '地図を開く'}</a></main></body></html>`, {
    status: 503, headers: { 'Content-Type': 'text/html; charset=utf-8' },
  });
}

async function cacheFirst(request, event) {
  const staticCache = await caches.open(STATIC_CACHE_NAME);
  // These are versioned same-origin files with identical content for every
  // request. A module's Origin header must not miss a worker-saved response
  // merely because the static server sets Vary: Origin.
  const cachedResponse = await staticCache.match(request, { ignoreVary: true }) || await (await caches.open(RUNTIME_CACHE_NAME)).match(request);
  if (cachedResponse) return cachedResponse;
  const response = await fetch(request);
  if (response.ok) {
    const copy = response.clone();
    event.waitUntil(caches.open(RUNTIME_CACHE_NAME).then(cache => cache.put(request, copy)).catch(() => {}));
  }
  return response;
}

self.addEventListener('install', event => {
  // Installation becomes usable only after every resource is saved. Updates
  // wait for existing tabs to close, keeping their old asset URLs available.
  event.waitUntil(saveOfflineMap());
});

self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(names => Promise.all(names
    .filter(name => name.startsWith(CACHE_PREFIX) && ![STATIC_CACHE_NAME, RUNTIME_CACHE_NAME].includes(name))
    .map(name => caches.delete(name))))
    .then(() => self.clients.claim()));
});

self.addEventListener('message', event => {
  if (event.data?.type === 'GET_OFFLINE_MAP_STATUS') {
    event.ports[0]?.postMessage({ type: 'OFFLINE_MAP_STATUS', state: 'ready', revision: PRECACHE_REVISION });
  }
});

self.addEventListener('fetch', event => {
  const { request } = event;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || isEditorPath(url.pathname) || url.pathname.startsWith('/api/')) return;
  if (request.mode === 'navigate') {
    event.respondWith(networkFirst(request));
  } else if (STATIC_PATH_PREFIXES.some(prefix => url.pathname.startsWith(prefix)) || APP_SHELL_URLS.includes(url.pathname)) {
    event.respondWith(cacheFirst(request, event));
  }
});
